#!/usr/bin/env bash
# Regenerate the base and engine layer locks: closures resolved by uv, entries copied verbatim from the main lock.

set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UV="${UV:-uv}"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

norm() {
  # PEP 503 name: lowercase, runs of - _ . become -.
  tr 'A-Z_.' 'a-z--' | sed 's/--*/-/g'
}

top_names() {
  # Package names a layer .in lists (comments and blank lines dropped).
  sed 's/#.*//' "$1" | awk 'NF { print $1 }' | norm
}

pinned_inputs() {
  # The main .in lines for the names in $2, so the layer resolves to the same version or URL.
  local main_in="$1" names="$2" line name
  while IFS= read -r line; do
    [[ -z "${line}" || "${line}" == \#* ]] && continue
    name="$(sed -E 's/[ =@<>~!;\[].*//' <<<"${line}" | norm)"
    if grep -qx "${name}" <<<"${names}"; then
      echo "${line}"
    fi
  done <"${main_in}"
}

extract() {
  # Copy the entries named on stdin-file $1 from lock $2, without the "# via" annotations.
  awk -v names="$1" '
    function norm(s) { s = tolower(s); gsub(/[_.]+/, "-", s); gsub(/-+/, "-", s); return s }
    BEGIN { while ((getline n < names) > 0) want[n] = 1 }
    /^[A-Za-z0-9]/ { split($0, a, /[ =@]/); keep = (norm(a[1]) in want); if (keep) found[norm(a[1])] = 1 }
    /^ *#/ { next }
    keep { print }
    END { for (n in want) if (!(n in found)) { print "missing from the main lock: " n > "/dev/stderr"; bad = 1 } exit bad }
  ' "$2"
}

for arch in x86_64 aarch64; do
  if [[ "${arch}" == x86_64 ]]; then
    main_in="${DIR}/requirements.in" main_lock="${DIR}/requirements.lock" suffix=""
  else
    main_in="${DIR}/requirements.aarch64.in" main_lock="${DIR}/requirements.aarch64.lock" suffix=".aarch64"
  fi
  for layer in base engine; do
    names="$(top_names "${DIR}/requirements.${layer}.in")"
    pinned_inputs "${main_in}" "${names}" >"${TMP}/${layer}.in"
    if [[ "$(wc -l <"${TMP}/${layer}.in")" -ne "$(wc -l <<<"${names}")" ]]; then
      echo "requirements.${layer}.in names a package that $(basename "${main_in}") does not pin" >&2
      exit 1
    fi
    "${UV}" pip compile --quiet "${TMP}/${layer}.in" -c "${main_in}" --python-version 3.11 \
      --python-platform "${arch}-manylinux_2_28" --no-header --no-annotate -o "${TMP}/${layer}.txt"
    sed -E 's/[ =@;].*//' "${TMP}/${layer}.txt" | awk 'NF' | norm | sort -u >"${TMP}/${layer}.names"
    out="${DIR}/requirements.${layer}${suffix}.lock"
    {
      echo "# Generated by layers.sh from requirements.${layer}.in: the ${layer} layer's closure, copied from $(basename "${main_lock}")."
      echo "# Do not edit; rerun pyenv/layers.sh after changing the main lock."
      extract "${TMP}/${layer}.names" "${main_lock}"
    } >"${out}.new"
    mv "${out}.new" "${out}"
    echo "$(basename "${out}"): $(wc -l <"${TMP}/${layer}.names") packages"
  done
done
